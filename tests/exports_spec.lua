local fx = load_module('tests/fivem.lua')

local function boot()
    fx.boot({ convars = { ['atlas:token'] = 'atl_live_x' }, load = { 'server/exports.lua' } })
    local suggested = {}
    Atlas.suggestPlaces = function(list) suggested[#suggested + 1] = list end
    return fx.state.exported, suggested
end

local function last()
    Atlas.jsReady = true
    Atlas.flush()
    local calls = fx.triggered('atlas:internal:batch')
    local batch = calls[#calls][1]
    return batch[#batch]
end

describe('exports.track', function()
    it('prefixes and sanitises the event name', function()
        local api = boot()
        expect(api.track('Shop Sale!', { n = 1 })).toBe(true)
        expect(last().type).toBe('custom.shop_sale_')
        expect(api.track('custom.heist.start', {})).toBe(true)
        expect(last().type).toBe('custom.heist.start')
        fx.teardown()
    end)

    it('caps the name length and rejects empty or non-string names', function()
        local api = boot()
        api.track(string.rep('a', 200), {})
        expect(#last().type).toBe(#'custom.' + 64)
        expect(api.track('', {})).toBe(false)
        expect(api.track(nil, {})).toBe(false)
        expect(api.track(42, {})).toBe(false)
        expect(Atlas.lastSeq()).toBe(1)
        fx.teardown()
    end)

    it('wraps scalar data and attributes the calling resource', function()
        local api = boot()
        fx.state.invoker = 'my-heist'
        api.track('score', 7)
        local ev = last()
        expect(ev.data).toEqual({ value = 7 })
        expect(ev.res).toBe('my-heist')
        fx.teardown()
    end)

    it('attaches the actor for a known player and ignores an unknown src', function()
        local api = boot()
        fx.addPlayer(5, { ped = { x = 1.0, y = 1.0, z = 1.0 } })
        Atlas.ensurePlayer(5)
        api.track('known', {}, 5)
        expect(last().src).toBe(5)
        api.track('unknown', {}, 77)
        expect(last().src).toBeNil()
        fx.teardown()
    end)
end)

describe('exports.track data', function()
    it('strips functions, cycles and non-finite numbers before the event is queued', function()
        local api = boot()
        local data = { ok = 1, fn = function() end, nan = 0 / 0 }
        data.loop = data
        expect(api.track('risky', data)).toBe(true)
        local ev = last()
        expect(ev.data.ok).toBe(1)
        expect(ev.data.fn).toBeNil()
        expect(ev.data.nan).toBeNil()
        expect(ev.data.loop.loop.loop.loop).toBeNil()
        fx.teardown()
    end)

    it('drops a scalar function instead of failing', function()
        local api = boot()
        expect(api.track('fn', function() end)).toBe(true)
        expect(last().data).toEqual({})
        fx.teardown()
    end)
end)

describe('exports.money', function()
    it('maps a positive delta to add and a negative one to remove', function()
        local api = boot()
        expect(api.money(nil, 250, 'bank', 'salary')).toBe(true)
        local add = last()
        expect(add.data).toEqual({ mtype = 'bank', action = 'add', amount = 250, delta = 250, reason = 'salary' })
        api.money(nil, -40)
        local rem = last()
        expect(rem.data.action).toBe('remove')
        expect(rem.data.amount).toBe(40)
        expect(rem.data.delta).toBe(-40)
        expect(rem.data.mtype).toBe('cash')
        expect(rem.data.reason).toBe('unknown')
        fx.teardown()
    end)

    it('rejects NaN, infinity, huge and non-numeric amounts', function()
        local api = boot()
        expect(api.money(nil, 0 / 0)).toBe(false)
        expect(api.money(nil, math.huge)).toBe(false)
        expect(api.money(nil, 2e12)).toBe(false)
        expect(api.money(nil, 'abc')).toBe(false)
        expect(api.money(nil, nil)).toBe(false)
        expect(Atlas.bufferDepth()).toBe(0)
        fx.teardown()
    end)

    it('truncates a long money type', function()
        local api = boot()
        api.money(nil, 1, string.rep('t', 100), 'x')
        expect(#last().data.mtype).toBe(32)
        fx.teardown()
    end)

    it('truncates long reasons to 128 characters', function()
        local api = boot()
        api.money(nil, 1, 'cash', string.rep('x', 500))
        expect(#last().data.reason).toBe(128)
        fx.teardown()
    end)

    it('takes a fresh position for a known player', function()
        local api = boot()
        fx.addPlayer(5, { ped = { x = 33.34, y = 44.46, z = 5.0 } })
        Atlas.ensurePlayer(5)
        api.money(5, 10, 'cash', 'test')
        expect(last().pos).toEqual({ 33.3, 44.5, 5.0 })
        fx.teardown()
    end)
end)

describe('exports.place', function()
    it('suggests a rounded place with a default kind and radius', function()
        local api, suggested = boot()
        expect(api.place('Pier', { x = 10.04, y = 20.06, z = 1.0 })).toBe(true)
        expect(suggested[1]).toEqual({ { 'Pier', 'custom', 10.0, 20.1, 30.0 } })
        api.place('Garage', { x = 1.0, y = 2.0 }, 12, 'garage')
        expect(suggested[2]).toEqual({ { 'Garage', 'garage', 1.0, 2.0, 12 } })
        fx.teardown()
    end)

    it('truncates names to 64 characters', function()
        local api, suggested = boot()
        api.place(string.rep('n', 100), { x = 1.0, y = 2.0 })
        expect(#suggested[1][1][1]).toBe(64)
        fx.teardown()
    end)

    it('rejects empty names, non-string names and bad coordinates', function()
        local api, suggested = boot()
        expect(api.place('', { x = 1.0, y = 2.0 })).toBe(false)
        expect(api.place(12, { x = 1.0, y = 2.0 })).toBe(false)
        expect(api.place('Pier', nil)).toBe(false)
        expect(api.place('Pier', { x = 'a', y = 2.0 })).toBe(false)
        expect(#suggested).toBe(0)
        fx.teardown()
    end)
end)
